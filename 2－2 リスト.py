#問題３（要素のスライス代入の違い）
#次のリストがあります。
colors = ['赤', '青', '緑', '黄']
#以下の2つの操作を、それぞれ別のコードとして書いてください。
#1．「青」の部分だけを「紫」に書き換える（リストの要素数は変わらないようにする）
